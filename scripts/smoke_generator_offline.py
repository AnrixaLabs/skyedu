"""Offline SkyED lesson-generation smoke test.

Exercises the REAL run_pipeline.py entrypoint in dry-run mode for every existing
non-NG lesson theme, without WordPress credentials, network, TTS, or image API.
Media files are NOT generated by this test: it verifies the parser, question
builder, local lesson shell, filename contracts and theme isolation only.

Usage: python scripts/smoke_generator_offline.py --report smoke-report.json
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile


SAMPLE = """#Title: Release QA - My Family Rooms

#Tags: family, home

#Vocabulary:
noun: living room-客厅, noun: kitchen-厨房, noun: bathroom-卫生间, noun: bedroom-卧室, noun: grandma-奶奶, noun: baby-宝宝, noun: grandpa-爷爷

#Sentences:
The baby is in the living room.
宝宝在客厅里。
Grandma is in the kitchen.
奶奶在厨房里。
Grandpa is in the bedroom.
爷爷在卧室里。
The bathroom is clean.
卫生间很干净。
"""

THEMES = ("sky", "sky_tiles", "fun_mission", "strict_dark")


def exercise(repo: Path, tmp: Path) -> dict:
    example = tmp / "homework-qa.txt"
    example.write_text(SAMPLE, encoding="utf-8")
    results = []
    for theme in THEMES:
        out = tmp / ("output-" + theme)
        env = dict(os.environ)
        env.update({
            "OUTPUT_DIR": str(out),
            "SKYED_DRY_RUN": "1",
            "IMG_BACKEND": "noop",
            "SKYED_SPECIAL_AUDIO_ENABLED": "0",
            "SKYED_ENABLE_SHARED_TAG_DISCOVERY": "0",
            "SKYED_NG_ACTION": "",
            "SKYED_PIPELINE_ENTRYPOINT": "",
            "WP_BASE_URL": "", "WP_BASE": "", "WP_USER": "",
            "WP_APP_PASSWORD": "", "WP_PUBLISH_STATUS": "draft",
            "QUIZ_PUBLIC_BASE": "", "TAGS_PUBLIC_BASE": "",
        })
        cmd = [sys.executable, "run_pipeline.py", "--input", str(example),
               "--theme", theme, "--dry-run", "--publish-status", "draft"]
        result = subprocess.run(cmd, cwd=repo, env=env,
                                text=True, stdout=subprocess.PIPE,
                                stderr=subprocess.STDOUT, timeout=90)
        if result.returncode:
            raise AssertionError(
                f"run_pipeline.py failed for {theme} code={result.returncode}\n"
                + result.stdout[-5000:])
        folders = [p for p in out.iterdir() if p.is_dir()] if out.exists() else []
        if len(folders) != 1:
            raise AssertionError(f"{theme}: expected one generated lesson, got {folders}")
        lesson = folders[0]
        for name in ("lesson.html", "quiz.json", "spec_debug.json", "lesson_manifest.json"):
            if not (lesson / name).is_file():
                raise AssertionError(f"{theme}: missing {name}")
        manifest = json.loads((lesson / "lesson_manifest.json").read_text(encoding="utf-8"))
        spec = json.loads((lesson / "spec_debug.json").read_text(encoding="utf-8"))
        quiz = json.loads((lesson / "quiz.json").read_text(encoding="utf-8"))
        html = (lesson / "lesson.html").read_text(encoding="utf-8")
        if len(spec.get("vocab", [])) != 7:
            raise AssertionError(f"{theme}: parser lost vocabulary {spec.get('vocab')}")
        if len(spec.get("sentences", [])) != 4:
            raise AssertionError(f"{theme}: parser lost sentences {spec.get('sentences')}")
        if manifest.get("theme") != theme:
            raise AssertionError(f"{theme}: manifest theme mismatch {manifest.get('theme')}")
        if not html.strip():
            raise AssertionError(f"{theme}: empty lesson HTML")
        questions = quiz.get("questions", [])
        if not questions:
            raise AssertionError(f"{theme}: no generated questions")
        if theme == "sky_tiles":
            if len(questions) != 5 or any(q.get("kind") != "listen_to_picture" for q in questions):
                raise AssertionError("sky_tiles must contain exactly 5 picture-listening questions")
        if theme in ("sky", "fun_mission", "strict_dark"):
            if not any(q.get("kind") == "sentence_cloze" for q in questions):
                raise AssertionError(f"{theme}: sentence-cloze questions were not generated")
        flattened = json.dumps(quiz, ensure_ascii=False)
        if "living-room.png" in flattened or "living-room.mp3" in flattened:
            raise AssertionError(f"{theme}: incorrect hyphenated media stem for living room")
        if "living_room.png" not in flattened and theme != "strict_dark":
            raise AssertionError(f"{theme}: expected living_room image reference absent")
        results.append({
            "theme": theme, "vocabulary": len(spec["vocab"]),
            "sentences": len(spec["sentences"]),
            "questions": len(questions),
            "kinds": sorted({q.get("kind", "") for q in questions}),
            "cloze_count": sum(q.get("kind") == "sentence_cloze" for q in questions),
            "dry_run": True, "media_generated": False,
            "wp_calls": 0, "status": "PASS",
        })
    return {
        "result": "PASS",
        "scope": "REAL pipeline dry-run (does not certify media generation/playback)",
        "publish_performed": False,
        "themes": results,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--report", type=Path)
    args = parser.parse_args(argv)
    try:
        with tempfile.TemporaryDirectory(prefix="skyed-offline-smoke-") as temporary:
            report = exercise(args.repo.resolve(), Path(temporary))
    except Exception as exc:
        report = {"result": "FAIL", "reason": str(exc), "publish_performed": False}
    content = json.dumps(report, ensure_ascii=False, indent=2)
    print(content)
    if args.report:
        args.report.parent.mkdir(parents=True, exist_ok=True)
        args.report.write_text(content + "\n", encoding="utf-8")
    return 0 if report["result"] == "PASS" else 2


if __name__ == "__main__":
    raise SystemExit(main())
